/**
 * Migrates Sign in with Apple users after an App Store Connect app transfer
 * (Toddly LLC -> Surmount Web Services LLC). See Apple TN3159.
 *
 *   node scripts/apple-migration/migrate.ts
 *
 * Reads:  .env.apple-migration, scripts/apple-migration/out/subs.json
 *         (export of auth.identities where provider = 'apple')
 * Writes: scripts/apple-migration/out/mapping.json  (resumable checkpoint)
 *         scripts/apple-migration/out/apply.sql     (review, then run against Supabase)
 *
 * Only calls Apple; never touches the database. Apple's migration endpoint is
 * only open to both teams for 60 days after the transfer completes.
 */

import { createPrivateKey, sign } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '../..');
const OUT = join(import.meta.dirname, 'out');
const MAPPING_PATH = join(OUT, 'mapping.json');
const APPLE = 'https://appleid.apple.com';

process.loadEnvFile(join(ROOT, '.env.apple-migration'));

type Team = { teamId: string; keyId: string; keyPath: string };
type Identity = { identity_id: string; user_id: string; sub: string; email: string | null };
type Migration = Identity & {
  transfer_sub?: string;
  new_sub?: string;
  new_email?: string | null;
  is_private_email?: boolean;
  error?: string;
};

function env(name: string): string {
  const v = process.env[name];
  if (!v) throw new Error(`Missing ${name} in .env.apple-migration`);
  return v;
}

const CLIENT_ID = env('APPLE_CLIENT_ID');
const FROM: Team = { teamId: env('FROM_TEAM_ID'), keyId: env('FROM_KEY_ID'), keyPath: env('FROM_KEY_PATH') };
const TO: Team = { teamId: env('TO_TEAM_ID'), keyId: env('TO_KEY_ID'), keyPath: env('TO_KEY_PATH') };

const b64url = (data: string | Buffer) => Buffer.from(data).toString('base64url');

function clientSecret(team: Team): string {
  const now = Math.floor(Date.now() / 1000);
  const header = b64url(JSON.stringify({ alg: 'ES256', kid: team.keyId }));
  const payload = b64url(
    JSON.stringify({ iss: team.teamId, iat: now, exp: now + 3600, aud: APPLE, sub: CLIENT_ID }),
  );
  const key = createPrivateKey(readFileSync(team.keyPath, 'utf8'));
  const sig = sign('sha256', Buffer.from(`${header}.${payload}`), { key, dsaEncoding: 'ieee-p1363' });
  return `${header}.${payload}.${b64url(sig)}`;
}

async function post(path: string, body: Record<string, string>, bearer?: string): Promise<any> {
  const res = await fetch(`${APPLE}${path}`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/x-www-form-urlencoded',
      ...(bearer ? { Authorization: `Bearer ${bearer}` } : {}),
    },
    body: new URLSearchParams(body),
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`${path} ${res.status}: ${text}`);
  return JSON.parse(text);
}

async function migrationToken(secret: string): Promise<string> {
  const data = await post('/auth/token', {
    grant_type: 'client_credentials',
    scope: 'user.migration',
    client_id: CLIENT_ID,
    client_secret: secret,
  });
  return data.access_token;
}

const sql = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);

function buildApplySql(rows: Migration[]): string {
  const values = rows
    .map(
      (m) =>
        `  (${sql(m.identity_id)}::uuid, ${sql(m.user_id)}::uuid, ${sql(m.sub)}, ${sql(m.new_sub)}, ${sql(m.new_email ?? null)}, ${m.is_private_email ? 'true' : 'false'})`,
    )
    .join(',\n');

  return `-- Generated by scripts/apple-migration/migrate.ts on ${new Date().toISOString()}
-- Remaps ${rows.length} Apple identities from team ${FROM.teamId} to team ${TO.teamId}.
begin;

create temp table apple_map (
  identity_id uuid primary key,
  user_id uuid not null,
  old_sub text not null,
  new_sub text not null unique,
  new_email text,
  is_private boolean not null
) on commit drop;

insert into apple_map values
${values};

-- Abort if any new sub is already attached to an identity (duplicate account created after the transfer).
do $$
declare conflicts text;
begin
  select string_agg(m.old_sub || ' -> ' || m.new_sub || ' (user ' || i.user_id || ')', ', ')
    into conflicts
    from apple_map m
    join auth.identities i on i.provider = 'apple' and i.provider_id = m.new_sub;
  if conflicts is not null then
    raise exception 'New Apple subs already in use: %', conflicts;
  end if;
end $$;

-- Abort if the identities no longer match the export.
do $$
declare matched int;
begin
  select count(*) into matched
    from apple_map m
    join auth.identities i on i.id = m.identity_id and i.provider = 'apple' and i.provider_id = m.old_sub;
  if matched <> (select count(*) from apple_map) then
    raise exception 'Only % of % identities match the export; re-export and re-run', matched, (select count(*) from apple_map);
  end if;
end $$;

create table if not exists public.apple_migration_backup (
  identity_id uuid primary key,
  user_id uuid not null,
  old_sub text not null,
  identity_data jsonb,
  user_email text,
  raw_user_meta_data jsonb,
  backed_up_at timestamptz not null default now()
);
alter table public.apple_migration_backup enable row level security;

insert into public.apple_migration_backup (identity_id, user_id, old_sub, identity_data, user_email, raw_user_meta_data)
select i.id, i.user_id, i.provider_id, i.identity_data, u.email, u.raw_user_meta_data
from apple_map m
join auth.identities i on i.id = m.identity_id
join auth.users u on u.id = i.user_id
on conflict (identity_id) do nothing;

update auth.identities i
set provider_id = m.new_sub,
    identity_data = i.identity_data
      || jsonb_build_object('sub', m.new_sub, 'provider_id', m.new_sub)
      || case when m.new_email is not null then jsonb_build_object('email', m.new_email) else '{}'::jsonb end,
    updated_at = now()
from apple_map m
where i.id = m.identity_id and i.provider_id = m.old_sub;

update auth.users u
set raw_user_meta_data = u.raw_user_meta_data
      || case when u.raw_user_meta_data ? 'sub' then jsonb_build_object('sub', m.new_sub, 'provider_id', m.new_sub) else '{}'::jsonb end
      || case when m.is_private and m.new_email is not null and u.raw_user_meta_data ? 'email' then jsonb_build_object('email', m.new_email) else '{}'::jsonb end,
    email = case when m.is_private and m.new_email is not null then m.new_email else u.email end,
    updated_at = now()
from apple_map m
where u.id = m.user_id;

commit;
`;
}

async function main() {
  const identities: Identity[] = JSON.parse(readFileSync(join(OUT, 'subs.json'), 'utf8'));
  const prior: Migration[] = existsSync(MAPPING_PATH) ? JSON.parse(readFileSync(MAPPING_PATH, 'utf8')) : [];
  const bySub = new Map(prior.map((m) => [m.sub, m]));
  const results: Migration[] = identities.map((i) => ({ ...i, ...bySub.get(i.sub), error: undefined }));
  const save = () => writeFileSync(MAPPING_PATH, JSON.stringify(results, null, 2));

  const fromSecret = clientSecret(FROM);
  const toSecret = clientSecret(TO);
  const fromToken = await migrationToken(fromSecret);
  const toToken = await migrationToken(toSecret);
  console.log(`Got migration tokens for ${FROM.teamId} and ${TO.teamId}`);

  for (const [n, m] of results.entries()) {
    if (m.new_sub) continue;
    try {
      if (!m.transfer_sub) {
        const t = await post(
          '/auth/usermigrationinfo',
          { sub: m.sub, target: TO.teamId, client_id: CLIENT_ID, client_secret: fromSecret },
          fromToken,
        );
        m.transfer_sub = t.transfer_sub;
      }
      const x = await post(
        '/auth/usermigrationinfo',
        { transfer_sub: m.transfer_sub!, client_id: CLIENT_ID, client_secret: toSecret },
        toToken,
      );
      m.new_sub = x.sub;
      m.new_email = x.email ?? null;
      m.is_private_email = x.is_private_email === true || x.is_private_email === 'true';
    } catch (e: any) {
      m.error = e.message;
    }
    save();
    console.log(`${n + 1}/${results.length} ${m.sub} -> ${m.new_sub ?? `ERROR ${m.error}`}`);
  }
  save();

  const done = results.filter((m) => m.new_sub);
  const failed = results.filter((m) => !m.new_sub);
  const emailChanges = done.filter((m) => m.is_private_email && m.new_email && m.new_email !== m.email);
  const realEmailMismatch = done.filter((m) => !m.is_private_email && m.new_email && m.new_email !== m.email);

  writeFileSync(join(OUT, 'apply.sql'), buildApplySql(done));

  console.log(`\nMigrated ${done.length}/${results.length}; failed ${failed.length}`);
  console.log(`Private relay emails changing: ${emailChanges.length}`);
  if (realEmailMismatch.length) console.log(`Non-relay email differs (left unchanged): ${realEmailMismatch.length}`);
  for (const f of failed) console.log(`  FAILED ${f.user_id} ${f.sub}: ${f.error}`);
  console.log(`\nWrote ${join(OUT, 'apply.sql')} - review before running.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
